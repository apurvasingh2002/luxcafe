    private void alterOrder(int orderId, String status, JButton btn) {
        if (btn.isEnabled()) {
            if (JOptionPane.showConfirmDialog(null, "Are you sure you want this order to be " + status, "Alert", JOptionPane.YES_NO_OPTION) == 0) {
                DBConnect connect = new DBConnect();
                boolean cancelFlag = status.equals("Canceled");
                if (cancelFlag) {
                    String remarks = JOptionPane.showInputDialog("Please enter remarks why this order was canceled");
                    if (remarks != null) {
                        if (!remarks.equals("")) {
                            connect.insertStatement("update `order` set status='" + status + "',remarks='" + remarks + "' where id=" + orderId, false);
                            cancelFlag = false;
                        }
                    }
                } else {
                    connect.insertStatement("update `order` set status='" + status + "' where id=" + orderId, false);
                    createPayment(orderId);
                }
                if (!cancelFlag) {
                    connect.prepareStatement("select table_id from `order` where id=" + orderId, false);
                    try {
                        if (connect.resultSet.next()) {
                            int tableId = connect.resultSet.getInt("table_id");
                            connect.insertStatement("update `table` set occupied=0 where id=" + tableId, false);
                        }
                    } catch (SQLException ex) {
                        Logger.getLogger(KOTForm.class.getName()).log(Level.SEVERE, null, ex);
                    }
                    Component[] components = btn.getParent().getComponents();
                    for (Component component : components) {
                        if (component instanceof JButton) {
                            component.setEnabled(false);
                        }
                    }
                    if (parentFrame != null) {
                        parentFrame.clearTable();
                    }
                }
            }
        }
    }

    private void updateKot(JButton btn, int orderId) {
        String tableName = jTabbedPane.getTitleAt(jTabbedPane.getSelectedIndex());
        String waiterName = "";
        String orderType = "";
        String customerName = "";
        for (Component component : btn.getParent().getComponents()) {
            if (component instanceof JLabel jLabel) {
                if (jLabel.getName().equals("waiterValueLabel")) {
                    waiterName = jLabel.getText();
                }
                if (jLabel.getName().equals("orderTypeValueLabel")) {
                    orderType = jLabel.getText();
                }
                if (jLabel.getName().equals("customerValueLabel")) {
                    String text = jLabel.getText();
                    if (!text.equals("Not selected")) {
                        customerName = text;
                    }
                }
            }
        }
        if (parentFrame != null) {
            parentFrame.setSelectedOrderId(orderId);
            parentFrame.updateMenuTable(updateButtonClicked(btn), tableName, waiterName, orderType, customerName);
            dispose();
        }
    }

    private void createPayment(int orderId) {
        DBConnect connect = new DBConnect();
        connect.prepareStatement("select sum(price) as total from order_details where order_id=" + orderId, false);
        try {
            if (connect.resultSet.next()) {
                int total = connect.resultSet.getInt("total");
                int customerId = getCustomerIdFromDB(orderId);
                if (customerId != 0) {
                    connect.insertStatement("insert into payment (order_id,amount,user_id,customer_id) "
                            + "values(" + orderId + "," + total + "," + parentFrame.loginId + "," + customerId + ")", false);
                } else {
                    connect.insertStatement("insert into payment (order_id,amount,user_id) values(" + orderId + "," + total + "," + parentFrame.loginId + ")", false);
                }
            }
        } catch (SQLException ex) {
            Logger.getLogger(KOTForm.class.getName()).log(Level.SEVERE, null, ex);
        }

    }

    private Object[][] updateButtonClicked(JButton btn) {
        Object[][] items = null;
        for (var comp : btn.getParent().getComponents()) {
            if (comp instanceof JScrollPane jScrollPane) {
                JViewport viewport = jScrollPane.getViewport();
                JTable table = (JTable) viewport.getView();
                DefaultTableModel dtm = (DefaultTableModel) table.getModel();
                items = new Object[dtm.getRowCount()][dtm.getColumnCount()];
                for (int i = 0; i < dtm.getRowCount(); i++) {
                    for (int j = 0; j < dtm.getColumnCount(); j++) {
                        items[i][j] = dtm.getValueAt(i, j);
                    }
                }
                break;
            }
        }
        return items;
    }

