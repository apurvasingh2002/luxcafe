    private int[] getOrderIdFromDB() {
        DBConnect connect = new DBConnect();
        connect.prepareStatement("select id from `order` where status='Pending'", false);
        int[] id = null;
        try {
            int i = 0;
            connect.resultSet.last();
            id = new int[connect.resultSet.getRow()];

            connect.resultSet.beforeFirst();
            while (connect.resultSet.next()) {
                id[i] = connect.resultSet.getInt("id");
                i++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(KOTForm.class.getName()).log(Level.SEVERE, null, ex);
        }
        return id;
    }

    private Object[][] getOrderDetailsFromDB(int orderId) {
        DBConnect connect = new DBConnect();
        connect.prepareStatement("select m.name,od.quantity,od.price from menu m join "
                + "order_details od on m.id = od.menu_id and od.order_id = " + orderId, false);
        Object[][] items = null;
        try {
            int i = 0;
            connect.resultSet.last();
            items = new Object[connect.resultSet.getRow()][4];
            connect.resultSet.beforeFirst();
            while (connect.resultSet.next()) {
                items[i][0] = i + 1;
                items[i][1] = connect.resultSet.getString("name");
                items[i][2] = connect.resultSet.getInt("quantity");
                items[i][3] = connect.resultSet.getInt("price");
                i++;
            }
        } catch (SQLException ex) {
            Logger.getLogger(KOTForm.class.getName()).log(Level.SEVERE, null, ex);
        }
        return items;
    }

    private String getTableNameFromDB(int orderId) {
        String tableName = "";
        DBConnect connect = new DBConnect();
        connect.prepareStatement("select name from `table` t join `order` o on o.table_id=t.id and o.id=" + orderId, false);
        try {
            if (connect.resultSet.next()) {
                tableName = connect.resultSet.getString("name");
            }
        } catch (SQLException ex) {
            Logger.getLogger(KOTForm.class.getName()).log(Level.SEVERE, null, ex);
        }
        return tableName;
    }

