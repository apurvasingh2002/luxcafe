    private void salesMonthComboBox1ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_salesMonthComboBox1ItemStateChanged
        if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
            int monthIndex = salesMonthComboBox1.getSelectedIndex();
            var time = LocalDate.now();
            if (comboTriggerFlag) {
                if (time.getMonthValue() > monthIndex + 1) {
                    YearMonth yearMonthObject = YearMonth.of(Integer.parseInt(salesYearComboBox1.getSelectedItem().toString()), monthIndex + 1);
                    salesDayComboBox1.removeAllItems();
                    for (int i = 0; i < yearMonthObject.lengthOfMonth(); i++) {
                        salesDayComboBox1.addItem(String.valueOf(i + 1));
                    }
                } else if (time.getMonthValue() == monthIndex + 1 && salesDayComboBox1.getItemCount() != time.getDayOfMonth()) {
                    salesDayComboBox1.removeAllItems();
                    for (int i = 0; i < time.getDayOfMonth(); i++) {
                        salesDayComboBox1.addItem(String.valueOf(i + 1));
                    }
                }
            }
        }
    }//GEN-LAST:event_salesMonthComboBox1ItemStateChanged

    private void salesMonthComboBox2ItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_salesMonthComboBox2ItemStateChanged
        if (evt.getStateChange() == java.awt.event.ItemEvent.SELECTED) {
            int monthIndex = salesMonthComboBox2.getSelectedIndex();
            var time = LocalDate.now();
            if (comboTriggerFlag) {
                if (time.getMonthValue() > monthIndex + 1) {
                    YearMonth yearMonthObject = YearMonth.of(Integer.parseInt(salesYearComboBox2.getSelectedItem().toString()), monthIndex + 1);
                    salesDayComboBox2.removeAllItems();
                    for (int i = 0; i < yearMonthObject.lengthOfMonth(); i++) {
                        salesDayComboBox2.addItem(String.valueOf(i + 1));
                    }
                    salesMonthComboBox1.removeAllItems();
                    for (int i = 0; i <= salesMonthComboBox2.getSelectedIndex(); i++) {
                        salesMonthComboBox1.addItem(salesMonthComboBox2.getItemAt(i));
                    }
                    salesMonthComboBox1.setSelectedIndex(salesMonthComboBox2.getSelectedIndex());
                } else if (time.getMonthValue() == monthIndex + 1 && salesDayComboBox2.getItemCount() != time.getDayOfMonth()) {
                    salesDayComboBox2.removeAllItems();
                    for (int i = 0; i < time.getDayOfMonth(); i++) {
                        salesDayComboBox2.addItem(String.valueOf(i + 1));
                    }
                    salesMonthComboBox1.removeAllItems();
                    for (int i = 0; i <= salesMonthComboBox2.getSelectedIndex(); i++) {
                        salesMonthComboBox1.addItem(salesMonthComboBox2.getItemAt(i));
                    }
                    salesMonthComboBox1.setSelectedIndex(salesMonthComboBox2.getSelectedIndex());
                }
            }
        }
    }//GEN-LAST:event_salesMonthComboBox2ItemStateChanged

