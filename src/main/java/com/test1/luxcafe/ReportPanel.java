    private void setSecondCreditTable(int customerId) {
        DBConnect connect = new DBConnect();
        connect.prepareStatement("select * from payment where customer_id=" + customerId, false);
        try {
            int sno = 1;
            DefaultTableModel dtm = (DefaultTableModel) creditTable.getModel();
            dtm.setRowCount(0);
            int totalAmount = 0;
            int totalDiscount = 0;
            while (connect.resultSet.next()) {
                int billId = connect.resultSet.getInt("id");
                int amount = connect.resultSet.getInt("amount");
                totalAmount += amount;
                int discount = connect.resultSet.getInt("discount");
                totalDiscount += discount;
                int receviedAmount = connect.resultSet.getInt("recevied_amount");
                String paymentDate = connect.resultSet.getString("payment_date");
                String orderType = getOrderTypefromDB(connect.resultSet.getInt("order_id"));
                dtm.addRow(new Object[]{sno, billId, amount, discount, receviedAmount, paymentDate.split(" ")[0], orderType});
                sno++;
            }
            if (dtm.getRowCount() > 0) {
                dtm.addRow(new Object[]{"", "", "", "", "", "", ""});
                dtm.addRow(new Object[]{"", "", "", "", "", "Total :", totalAmount});
                dtm.addRow(new Object[]{"", "", "", "", "", "Discount :", totalDiscount});
                dtm.addRow(new Object[]{"", "", "", "", "", "Net Total :", totalAmount - totalDiscount});
            }
        } catch (SQLException ex) {
            Logger.getLogger(ReportPanel.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

