    private boolean checkDataExits(String statement) {
        boolean flag = true;
        DBConnect connect = new DBConnect();
        connect.prepareStatement(statement, false);
        try {
            if (connect.resultSet.next()) {
                flag = connect.resultSet.getInt("total") > 0;
            }
        } catch (SQLException ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
        return flag;
    }

    public void setMenuTable() {
        DBConnect connect = new DBConnect();
        connect.prepareStatement("select * from menu ", false);
        DefaultTableModel model = (DefaultTableModel) menuTable.getModel();
        model.setRowCount(0);
        try {
            while (connect.resultSet.next()) {
                int id = connect.resultSet.getInt("id");
                String name = connect.resultSet.getString("name");
                String description = connect.resultSet.getString("description");
                int price = connect.resultSet.getInt("price");
                String category = connect.resultSet.getString("category");
                Object[] rowData = {id, name, description, price, category};
                model.addRow(rowData);
            }
        } catch (SQLException ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

