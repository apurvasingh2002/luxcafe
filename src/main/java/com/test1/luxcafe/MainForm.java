    public void setUsernameFromDB(int id) {
        if (loginId != 0) {
            DBConnect connect = new DBConnect();
            connect.prepareStatement("select username from `user` where id=" + id, false);
            try {
                if (connect.resultSet.next()) {
                    loginLabel.setText("Welcome "+connect.resultSet.getString("username").toUpperCase());
                }
            } catch (SQLException ex) {
                Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }

