    private void phoneTextFieldKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_phoneTextFieldKeyTyped
        char c = evt.getKeyChar();
        if (!("" + c).matches("[0-9]")) {
            evt.consume();
        } else {
            if (phoneTextField.getText().length() >= 10) {
                evt.consume();
            }
        }
    }//GEN-LAST:event_phoneTextFieldKeyTyped

    private Boolean checkVaue() {
        String firstName = firstNameTextField.getText();
        String lastName = LastNameTextField.getText();
        String phone = phoneTextField.getText();

        boolean flag = true;
        if (!checkEmptyString(firstName, jLabel2)) {
            flag = false;
        }
        if (!checkEmptyString(lastName, jLabel3)) {
            flag = false;
        }
        if (!checkEmptyString(phone, jLabel4)) {
            flag = false;
        } else {
            if (phone.length() != 10) {
                if (!jLabel4.getText().contains("*")) {
                    jLabel4.setText(jLabel4.getText().concat(" *"));
                    jLabel4.setForeground(Color.red);

                }
                flag = false;
            } else {
                jLabel4.setText(jLabel4.getText().split("\\*")[0]);
                jLabel4.setForeground(Color.BLACK);
            }
        }
        return flag;
    }

    private boolean checkEmptyString(String text, JLabel label) {
        boolean flag = true;
        if (text.equals("")) {
            if (!label.getText().contains("*")) {
                label.setText(label.getText().concat(" *"));
                label.setForeground(Color.red);
            }
            flag = false;
        } else {
            label.setText(label.getText().split("\\*")[0]);
            label.setForeground(Color.BLACK);
        }
        return flag;
    }

