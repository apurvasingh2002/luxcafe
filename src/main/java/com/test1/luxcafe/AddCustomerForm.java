    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        if (checkVaue()) {
            String firstName = firstNameTextField.getText();
            String lastName = LastNameTextField.getText();
            String phone = phoneTextField.getText();
            String email = emailTextField.getText();
            DBConnect connect = new DBConnect();
            if (id != 0) {
                connect.insertStatement("update customer set first_name='" + firstName + "',last_name='"
                        + lastName + "',phone='" + phone + "',email='" + email + "' where id=" + id, false);
            } else {
                connect.insertStatement("insert into customer(first_name,last_name,phone,email) "
                        + "values('" + firstName + "','" + lastName + "','" + phone + "','" + email + "')", false);
            }
            if (parentForm != null) {
                parentForm.setCustomerData();
                parentForm.toFront();
                parentForm.setEnabled(true);
            } else if (mainForm != null) {
                mainForm.setCustomerTable();
                mainForm.toFront();
                mainForm.setEnabled(true);
            }
            dispose();
        }
    }//GEN-LAST:event_jButton1MouseClicked

