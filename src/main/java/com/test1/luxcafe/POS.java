    private void menuTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_menuTableMouseClicked
        if (evt.getClickCount() == 2 && !evt.isConsumed()) {
            evt.consume();
            DefaultTableModel dtm = (DefaultTableModel) menuTable.getModel();
            int selectedRow = menuTable.getSelectedRow();
            int qty = (int) dtm.getValueAt(selectedRow, 2);
            if (qty > 1) {
                int unitPrice = (int) dtm.getValueAt(selectedRow, 3) / qty;
                int totalPrice = (int) dtm.getValueAt(selectedRow, 3) - unitPrice;
                dtm.setValueAt(totalPrice, selectedRow, 3);
                dtm.setValueAt(qty - 1, selectedRow, 2);
            } else {
                dtm.removeRow(selectedRow);
            }
            int total = 0;
            for (int i = 0; i < dtm.getRowCount(); i++) {
                dtm.setValueAt(i + 1, i, 0);
                total += (int) dtm.getValueAt(i, 3);
            }
            totalLabel.setText(String.valueOf(total));
        }
    }//GEN-LAST:event_menuTableMouseClicked

