    private void setOrder(String name, int amount) {
        DefaultTableModel dtm = (DefaultTableModel) menuTable.getModel();
        int rowCount = menuTable.getRowCount();
        int sno = rowCount + 1;
        String item = name;
        int qty = 1;
        int price = amount;
        int total = 0;
        if (rowCount > 0) {
            boolean rowFound = false;
            for (int i = 0; i < rowCount; i++) {
                if (menuTable.getValueAt(i, 1).equals(item)) {
                    qty += (int) menuTable.getValueAt(i, 2);
                    price += (int) menuTable.getValueAt(i, 3);
                    menuTable.setValueAt(qty, i, 2);
                    menuTable.setValueAt(price, i, 3);
                    rowFound = true;
                    break;
                }
            }
            if (!rowFound) {
                Object[] rowData = {sno, item, qty, price};
                dtm.addRow(rowData);
            }
        } else {
            Object[] rowData = {sno, item, qty, price};
            dtm.addRow(rowData);
        }
        for (int i = 0; i < menuTable.getRowCount(); i++) {
            total += (int) menuTable.getValueAt(i, 3);
        }
        totalLabel.setText(String.valueOf(total) + "/-");
    }

