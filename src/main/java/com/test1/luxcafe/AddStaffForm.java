    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        if (checkVaue()) {
            DBConnect connect = new DBConnect();
            String firstName = jTextField1.getText();
            String lastName = jTextField2.getText();
            String position = jTextField3.getText();
            String phone = jTextField4.getText();
            String email = jTextField5.getText();
            if (id == 0) {
                connect.insertStatement("insert into staff(first_name,last_name,position,phone,email) "
                        + "values('" + firstName + "','" + lastName + "','" + position + "','" + phone + "','" + email + "') ", false);
            } else {
                connect.insertStatement("update staff set first_name='" + firstName + "' ,last_name='" + lastName + "',position='"
                        + position + "',phone='" + phone + "',email='" + email + "' where id=" + id, false);
            }
            if (parentFrame != null) {
                parentFrame.toFront();
                parentFrame.setEnabled(true);
                parentFrame.setStaffTable();
            }
            dispose();
        }
    }//GEN-LAST:event_jButton1MouseClicked

