    private Boolean checkVaue() {
        String firstName = jTextField1.getText();
        String lastName = jTextField2.getText();
        String position = jTextField3.getText();
        String phone = jTextField4.getText();
//        String email = jTextField5.getText();   
        boolean flag = true;
        if (!checkEmptyString(firstName, jLabel1)) {
            flag = false;
        }
        if (!checkEmptyString(lastName, jLabel2)) {
            flag = false;
        }
        if (!checkEmptyString(position, jLabel3)) {
            flag = false;
        }
        if (!checkEmptyString(phone, jLabel4)) {
            flag = false;
        }
        return flag;
    }

    private boolean checkEmptyString(String text, JLabel label) {
        boolean flag = true;
        if (text.equals("")) {
            if (!label.getText().contains("*")) {
                label.setText(label.getText().concat(" *"));
                label.setForeground(Color.red);
            }
            flag = false;
        } else {
            label.setText(label.getText().split("\\*")[0]);
            label.setForeground(Color.BLACK);
        }
        return flag;
    }

