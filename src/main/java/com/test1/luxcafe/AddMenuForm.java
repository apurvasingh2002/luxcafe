    private Boolean checkVaue() {
        String name = jTextField1.getText();
//        String description = jTextField2.getText();
        String price = jTextField3.getText();

        boolean flag = true;
        if (!checkEmptyString(name, jLabel1)) {
            flag = false;
        }
        if (!checkEmptyString(price, jLabel3)) {
            flag = false;
        }

        return flag;
    }

    private boolean checkEmptyString(String text, JLabel label) {
        boolean flag = true;
        if (text.equals("")) {
            if (!label.getText().contains("*")) {
                label.setText(label.getText().concat(" *"));
                label.setForeground(Color.red);
            }
            flag = false;
        } else {
            label.setText(label.getText().split("\\*")[0]);
            label.setForeground(Color.BLACK);
        }
        return flag;
    }

