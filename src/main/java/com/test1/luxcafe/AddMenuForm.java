    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
        if (checkVaue()) {
            int price = Integer.parseInt(jTextField3.getText());
            DBConnect connect = new DBConnect();
            String name = jTextField1.getText();
            String description = jTextField2.getText();
            String category = jComboBox1.getSelectedItem().toString();
            if (id == 0) {
                connect.insertStatement("insert into menu(name,description,price,category) values('" + name + "','" + description + "'," + price + ",'" + category + "') ", false);
            } else {
                connect.insertStatement("update menu set name='" + name + "' ,description='" + description + "',price=" + price + ",category='" + category + "' where id=" + id, false);
            }
            if (parentFrame != null) {
                parentFrame.setEnabled(true);
                parentFrame.setMenuTable();
            }
            dispose();
        }
    }//GEN-LAST:event_jButton1MouseClicked

